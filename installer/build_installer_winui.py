"""构建 解析下载器 WinUI 版 的 NSIS 安装包（2026-10-31 新建）。

与 Flutter 版的 build_installer.py 平行，互不影响：
  Flutter 版: flutter build windows -> build/staging  -> installer/解析下载器.nsi
  WinUI  版: dotnet build -c Release -> build/winui_staging -> installer/解析下载器_winui.nsi

**为什么用 dotnet build 的输出、而不用 dotnet publish**（2026-10-31 实测）：
  `dotnet publish` 产出的目录里**没有 App.xbf / Pages/*.xbf**（XAML 编译产物），
  也没有合并好的 解析下载器.pri —— 直接跑必崩：
    Microsoft.UI.Xaml.Markup.XamlParseException: XAML parsing failed.
    at ParseDl.MainWindow..ctor()  (MainWindow.xaml.cs:line 24)
  而 `dotnet build -c Release -p:Platform=x64` 的输出目录
  (`ParseDl/bin/x64/Release/net10.0-windows10.0.26100.0/win-x64`) 带齐 240 个文件
  （含 App.xbf / Pages/*.xbf / 解析下载器.pri）且实测能正常启动。
  所以**安装源取 build 输出目录**，不要对它再跑 publish。
"""
import os, shutil, subprocess, sys, time

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PUBLISH = os.path.join(
    PROJECT, "ParseDl", "bin", "x64", "Release",
    "net10.0-windows10.0.26100.0", "win-x64",
)
STAGING = os.path.join(PROJECT, "build", "winui_staging")
NSI = os.path.join(PROJECT, "installer", "解析下载器_winui.nsi")
EXE = "解析下载器.exe"
VERSION = "1.5"
OUT_NAME = f"解析下载器_{VERSION}_x64-setup.exe"
OUT_DIR = os.environ.get("INSTALLER_OUT_DIR") or os.path.join(PROJECT, "build", "dist")

EXCLUDE_DIRS = {"userdata"}
EXCLUDE_FILES = {"解析下载器.pdb"}
NSIS_DIR = os.environ.get("NSIS_DIR") or r"C:/Program Files (x86)/NSIS"


def ensure_bom(path):
    with open(path, "rb") as f:
        data = f.read()
    if not data.startswith(b"\xef\xbb\xbf"):
        with open(path, "wb") as f:
            f.write(b"\xef\xbb\xbf" + data)
        print("[0] 补 UTF-8 BOM:", os.path.basename(path))


def rmtree_retry(path, attempts=5):
    for i in range(1, attempts + 1):
        try:
            shutil.rmtree(path)
            return
        except PermissionError:
            if i == attempts:
                raise
            print(f"    删除被占用，{i}/{attempts - 1} 重试…")
            time.sleep(1.5)


def main():
    if not os.path.exists(os.path.join(PUBLISH, EXE)):
        print(f"ERROR: 没找到 {PUBLISH}\\{EXE}")
        print("      先跑：dotnet build ParseDl/ParseDl.csproj -c Release -p:Platform=x64")
        sys.exit(1)
    makensis = os.path.join(NSIS_DIR, "makensis.exe")
    if not os.path.exists(makensis):
        print("ERROR: 找不到 makensis.exe：", makensis)
        sys.exit(1)
    ensure_bom(NSI)

    if os.path.exists(STAGING):
        rmtree_retry(STAGING)
    os.makedirs(STAGING, exist_ok=True)

    count = 0
    for root, dirs, names in os.walk(PUBLISH):
        dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS]
        for n in names:
            if n in EXCLUDE_FILES:
                continue
            s = os.path.join(root, n)
            d = os.path.join(STAGING, os.path.relpath(s, PUBLISH))
            os.makedirs(os.path.dirname(d), exist_ok=True)
            shutil.copy2(s, d)
            count += 1
    print(f"[1] staging 拷贝 {count} 个文件 -> {STAGING}")

    # 卸载清单（逐行 Delete），落在 build/ 而不是 staging/
    nsh = os.path.join(PROJECT, "build", "_uninst_files_winui.nsh")
    file_list = sorted(
        os.path.relpath(os.path.join(r, n), STAGING).replace("\\", "/")
        for r, _, ns in os.walk(STAGING) for n in ns
    )
    with open(nsh, "w", encoding="utf-8") as f:
        f.write("; Auto-generated by build_installer_winui.py — 卸载时逐行 Delete\n\n")
        for rel in file_list:
            f.write(f'  Delete "$INSTDIR\\{rel}"\n')
    print(f"[2] 生成 _uninst_files_winui.nsh（{len(file_list)} 项）")

    print(f"[3] makensis {NSI}")
    r = subprocess.run([makensis, f"/DVERSION={VERSION}", NSI], capture_output=True)
    out = (r.stdout or b"").decode("gbk", errors="replace")
    err = (r.stderr or b"").decode("gbk", errors="replace")
    print(out[-4000:])
    if r.returncode != 0:
        print("makensis ERROR:", err[-2000:])
        sys.exit(1)

    produced = os.path.join(PROJECT, "installer", OUT_NAME)
    if not os.path.exists(produced):
        print("ERROR: 期望产物不存在:", produced)
        sys.exit(1)
    os.makedirs(OUT_DIR, exist_ok=True)
    final = os.path.join(OUT_DIR, OUT_NAME)
    if os.path.abspath(produced) != os.path.abspath(final):
        shutil.copy2(produced, final)
    size = os.path.getsize(final) / 1024 / 1024
    print(f"[4] 完成: {final}  ({size:.1f} MB)")


if __name__ == "__main__":
    main()
